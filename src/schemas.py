from enum import Enum
from pydantic import BaseModel, Field


class RegionName(str, Enum):
    MUMBAI = "mumbai"
    RAJASTHAN = "rajasthan"
    STOCKHOLM = "stockholm"
    OREGON = "oregon"


class JobStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED_SLA = "failed_sla"


class Job(BaseModel):
    """Represents a discrete AI workload extracted from cluster traces."""
    job_id: str = Field(..., description="Unique job identifier from trace")
    arrival_time_hr: int = Field(..., ge=0, description="Hour the job arrived in the queue")
    duration_hrs: int = Field(..., gt=0, description="Wall-clock hours required to execute")
    energy_per_hr_kwh: float = Field(..., gt=0.0, description="Base server compute energy per hour")
    deadline_hrs: int = Field(..., gt=0, description="SLA: absolute hour by which execution must finish")
    priority: int = Field(default=1, ge=1, le=5, description="1=Batch/Tolerant, 5=High priority")


class HourlyEnvironment(BaseModel):
    """Environmental profile of a single region at a specific hour."""
    region: RegionName
    hour: int = Field(..., ge=0, le=8760, description="Simulated timeline hour (0 to 8760)")
    wet_bulb_temp_c: float = Field(..., description="Ambient wet-bulb temperature in Celsius")
    carbon_intensity_g_kwh: float = Field(..., ge=0.0, description="Grid carbon intensity in gCO2eq/kWh")
    water_stress_multiplier: float = Field(default=1.0, ge=1.0, description="Regional drought scarcity factor")
    electricity_cost_usd_kwh: float = Field(..., ge=0.0, description="Local electricity price per kWh")
    pue: float = Field(..., ge=1.0, description="Power Usage Effectiveness")
    wue_site: float = Field(..., ge=0.0, description="On-site cooling water evaporated in Liters/kWh")


class ScheduleDecision(BaseModel):
    """Output generated by a scheduling policy for a specific job."""
    job_id: str
    selected_region: RegionName
    start_hour: int
    finish_hour: int
    sla_met: bool
    total_energy_kwh: float
    total_carbon_kg: float
    total_water_liters: float
    total_cost_usd: float
    pareto_score: float